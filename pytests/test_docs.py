"""Документы по матрице: cause_effect_matrix.md и .html, VOTING.md, FAT_protocol.md — та же модель, что и код."""

from __future__ import annotations

import re
from html.parser import HTMLParser

from cemgen import fat
from cemgen.generate import Outputs
from cemgen.model import Matrix

VOID = {"meta", "br", "link", "img", "hr", "input", "col"}


class _Balance(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.stack: list[str] = []
        self.errors: list[str] = []
        self.tags: list[tuple[str, dict[str, str | None]]] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.tags.append((tag, dict(attrs)))
        if tag not in VOID:
            self.stack.append(tag)

    def handle_endtag(self, tag: str) -> None:
        if not self.stack or self.stack[-1] != tag:
            self.errors.append(f"</{tag}> при открытом {self.stack[-1:] or 'ничего'}")
            return
        self.stack.pop()


def test_cem_md_matrix_matches_model(demo: Matrix, demo_outputs: Outputs) -> None:
    md = demo_outputs.files["docs/cause_effect_matrix.md"]
    assert md.startswith("<!-- AUTO-GENERATED by cemgen ")
    rows = [line for line in md.splitlines() if re.match(r"^\| \d+ \| \*\*", line)]
    assert len(rows) == len(demo.causes)
    for cause, row in zip(demo.causes, rows, strict=True):
        cells = [c.strip() for c in row.strip("|").split("|")]
        marks = cells[6:]
        assert [m == "**X**" for m in marks] == [e.no in cause.effects for e in demo.effects]
    for effect in demo.effects:
        assert f"`16#{demo.effect_mask(effect.no):04X}`" in md
    assert "**`16#CD40`**" in md
    assert "Внимание." in md and "ГОСТ Р МЭК 61511" in md


