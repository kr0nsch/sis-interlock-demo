def test_fat_step_results_mapping(demo: Matrix) -> None:
    cases = [
        fat.CaseResult("Matrix_PSHH101Demand_TripsOwnEffects", "PASS", ""),
        fat.CaseResult("Matrix_PSHH101Delay_TripsExactlyAtDelay", "PASS", ""),
        fat.CaseResult("Matrix_PSLL101Demand_TripsOwnEffects", "PASS", ""),
        fat.CaseResult("Matrix_PSLL101Delay_TripsExactlyAtDelay", "FAIL", "PSLL101: latched causes exactly at delay"),
        fat.CaseResult("VoteTruth_Eval1oo1VT_MatchesTable", "SKIP", ""),
    ]
    results = fat.step_results(demo, cases)
    assert results["FAT-03-01"] == (fat.RESULT_PASS, "тестов 2")
    assert results["FAT-03-02"][0] == fat.RESULT_FAIL and "exactly at delay" in results["FAT-03-02"][1]
    assert results["FAT-03-03"][0] == fat.RESULT_NONE
    assert results["FAT-04-91"][0] == fat.RESULT_NONE  # только пропущенные тесты


def test_fat_truth_steps_cover_both_models_and_all_rows(demo: Matrix) -> None:
    steps = [step for s in fat.build_sections(demo) for step in s.steps if step.id.startswith("FAT-04-9")]
    assert [s.id for s in steps] == ["FAT-04-91", "FAT-04-92", "FAT-04-93", "FAT-04-94"]
    rows = []
    for step in steps:
        match = re.search(r"строк (\d+)", step.expected)
        assert match is not None, step.expected
        rows.append(int(match.group(1)))
    assert rows == [60, 432, 432, 3264] and sum(rows) == 4188  # 300 строк F_VoteEval + 3888 FB_Voting
    assert all(any(t.startswith("VoteTruth_") for t in s.autotests) for s in steps)
    assert all(any(t.startswith("VoteTable_") for t in s.autotests) for s in steps)


def test_fat_step_needs_results_for_every_pattern(demo: Matrix) -> None:
    truth = [fat.CaseResult(f"VoteTruth_Eval1oo1{p}_MatchesTable", "PASS", "") for p in ("VT", "DS", "DA")]
    table = [fat.CaseResult(f"VoteTable_Eval1oo1{p}_MatchesModel", "PASS", "") for p in ("VT", "DS", "DA")]
    only_truth = fat.step_results(demo, truth)["FAT-04-91"]
    assert only_truth[0] == fat.RESULT_NONE and "VoteTable_*1oo1*" in only_truth[1]
    assert fat.step_results(demo, truth + table)["FAT-04-91"] == (fat.RESULT_PASS, "тестов 6")
    assert fat.step_results(demo, truth + table)["FAT-04-92"][0] == fat.RESULT_NONE  # 1oo2 не 1oo1


def test_html_self_contained(demo: Matrix, demo_outputs: Outputs) -> None:
    html = demo_outputs.files["docs/cause_effect_matrix.html"]
    assert html.startswith("<!doctype html>")
    assert not re.search(r"(?i)(https?:|//cdn|<link\b|<img\b|src=|@import|url\()", html)
    assert "prefers-color-scheme: dark" in html
    assert "@page { size: A3 landscape" in html
    assert "writing-mode: vertical-rl" in html and "position: sticky" in html
    assert html.index("ВНИМАНИЕ.") < html.index('<table class="cem">')  # дисклеймер вверху
    parser = _Balance()
    parser.feed(html)
    assert parser.errors == [] and parser.stack == []
    marks = html.count('<span class="x">X</span>') - 1  # минус пример в легенде
    assert marks == sum(len(c.effects) for c in demo.causes)
    heads = [attrs for tag, attrs in parser.tags if tag == "th" and "eff" in (attrs.get("class") or "").split()]
    assert len(heads) == len(demo.effects)
    for effect in demo.effects:
        assert f">{demo.effect_mask(effect.no):04X}<" in html
