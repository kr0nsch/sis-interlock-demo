    lines += [
        f"// Автор:      <ИМЯ ФАМИЛИЯ>; код — генератор {GENERATOR}",
        "// Версия:     0.1.0",
        f"// Документ:   {DOC}",
    ]
    return AUTO + "\n".join(lines) + "\n" + WARNING


