def gvl_file(suites: list[Suite]) -> str:
    width = max(len(s.instance) for s in suites)
    tw = max(len(s.name) for s in suites) + 1
    lines = [
        object_header(
            [
                "экземпляры сгенерированных наборов таблиц истинности голосования. Объявление",
                "экземпляра регистрирует набор в coUnit; {attribute 'linkalways'} обязателен: на GVL",
                "никто не ссылается, без атрибута CODESYS 3.5.17 не включает её в приложение.",
            ]
        ).rstrip("\n"),
        "{attribute 'qualified_only'}",
        "{attribute 'linkalways'}",
        "VAR_GLOBAL",
    ]
    for s in suites:
        lines.append(f"    {s.instance.ljust(width)} : {(s.name + ';').ljust(tw)}   // {s.comment}")
    lines.append("END_VAR")
    return "\n".join(lines) + "\n"


def build() -> dict[str, str]:
    """Все сгенерированные файлы: путь от корня → текст."""
    suites = plan_suites()
    files: dict[str, str] = {}
    files.update(rig_files())
    for suite in suites:
        assert suite.asserts() < MAX_ASSERTS_PER_SUITE, (suite.name, suite.asserts())
        assert len(suite.tables) <= MAX_TESTS_PER_SUITE, suite.name
        files.update(suite_files(suite))
    files[GVL_PATH] = gvl_file(suites)
    for path, text in files.items():
        for no, line in enumerate(text.split("\n"), 1):
            assert len(line) <= MAX_LINE, f"{path}:{no}: строка длиннее {MAX_LINE}"
            assert line == line.rstrip(), f"{path}:{no}: хвостовые пробелы"
            assert "\t" not in line, f"{path}:{no}: табуляция"
    return files


def existing_generated(root: Path) -> set[str]:
    gen = root / GEN_DIR
    found = {p.relative_to(root).as_posix() for p in gen.rglob("*.st")} if gen.is_dir() else set()
    if (root / GVL_PATH).is_file():
        found.add(GVL_PATH)
    return found


def compare(root: Path, files: dict[str, str]) -> list[str]:
    """Отличия: изменённые, новые и лишние файлы."""
    problems = []
    for rel, text in sorted(files.items()):
        path = root / rel
        if not path.is_file():
            problems.append(f"нет файла: {rel}")
        elif path.read_bytes() != text.encode("utf-8"):
            problems.append(f"отличается: {rel}")
    for rel in sorted(existing_generated(root) - set(files)):
        problems.append(f"лишний файл: {rel}")
    return problems


def write(root: Path, files: dict[str, str]) -> int:
    changed = 0
    for rel in sorted(existing_generated(root) - set(files)):
        (root / rel).unlink()
        changed += 1
    for rel, text in sorted(files.items()):
        path = root / rel
        data = text.encode("utf-8")
        if path.is_file() and path.read_bytes() == data:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        changed += 1
    for directory in sorted((root / GEN_DIR).glob("*"), reverse=True):
        if directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()
    return changed


def stats(files: dict[str, str]) -> tuple[int, int, int]:
    suites = plan_suites()
    tests = sum(len(s.tables) for s in suites)
    asserts = sum(s.asserts() for s in suites)
    return len(suites), tests, asserts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="только сравнить с файлами репозитория")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="корень репозитория")
    args = parser.parse_args(argv)
    files = build()
    n_suites, n_tests, n_asserts = stats(files)
    if args.check:
        problems = compare(args.root, files)
        for line in problems:
            print(line)
        if problems:
            print(f"gen_voting_tests: расхождений {len(problems)} — запустите python {GENERATOR}")
            return 1
        print(f"gen_voting_tests: совпадает (наборов {n_suites}, тестов {n_tests}, ассертов {n_asserts})")
        return 0
    changed = write(args.root, files)
    print(
        f"gen_voting_tests: файлов {len(files)}, изменено {changed}; "
        f"наборов {n_suites}, тестов {n_tests}, ассертов {n_asserts}"
    )
    return 0


