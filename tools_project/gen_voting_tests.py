def test_method_files(table: Table) -> dict[str, str]:
    expected = table.expected()
    n = M.arch_channels(table.arch)
    if table.level == 1:
        what = (
            f"F_VoteEval, схема {table.arch_name}, политика {POLICY_ABBR[table.policy]}: "
            f"все {len(expected)} сочетаний состояний {n} каналов"
        )
        call = "EvalRow"
        kind = "E_SisInputKind.Discrete"
    else:
        what = (
            f"FB_Voting, схема {table.arch_name}, политика {POLICY_ABBR[table.policy]}, "
            f"вход {KIND_ABBR[table.kind]}: все {len(expected)} сочетаний"
        )
        call = "FbRow"
        kind = KIND_ST[table.kind]
    decl = (
        AUTO
        + f"// {what}\n"
        + "// (требование × достоверность × запрос байпаса по каналу — для FB_Voting); ожидаемые значения —\n"
        + "// эталонная модель tools_project/vote_model.py. Один AssertEquals_BYTE на строку.\n"
        + f"METHOD PRIVATE {table.method_name}\n"
        + "VAR\n"
        + "    fbRig : FB_VoteTableRig;   // стенд таблиц (новый экземпляр на тест)\n"
        + "    bRes  : BYTE;              // код результата строки\n"
        + "END_VAR\n"
    )
    lines = [
        AUTO.rstrip("\n"),
        f"coUnit.TEST('{table.test_name}');",
        f"fbRig.Setup(eArch := {ARCH_ST[table.arch]}, ePolicy := {POLICY_ST[table.policy]},",
        f"    eInput := {kind});",
    ]
    for row, value in enumerate(expected):
        msg = row_message(table, row, value)
        lines.append(f"bRes := fbRig.{call}(uiRow := {row});")
        lines.append(f"AssertEquals_BYTE(Expected := 16#{value:02X}, Actual := bRes,")
        lines.append(f"    Message := '{msg}');")
    lines.append("coUnit.TEST_FINISHED();")
    impl = "\n".join(lines) + "\n"
    base = f"{table.method_name}.method"
    return {f"{base}.decl.st": decl, f"{base}.impl.st": impl}


def suite_files(suite: Suite) -> dict[str, str]:
    rows = suite.asserts()
    decl = (
        object_header(
            [
                f"набор таблиц истинности голосования — {suite.comment}.",
                f"Тестов {len(suite.tables)}, ассертов {rows} (по одному на строку). Экземпляр — в",
                "GVL_TestsTruthTables: объявление регистрирует набор в coUnit.",
            ]
        )
        + f"FUNCTION_BLOCK {suite.name} EXTENDS coUnit.FB_TestSuite\n"
    )
    body = [AUTO.rstrip("\n")] + [f"{t.method_name}();" for t in suite.tables]
    files = {f"{suite.name}.decl.st": decl, f"{suite.name}.impl.st": "\n".join(body) + "\n"}
    for table in suite.tables:
        files.update(test_method_files(table))
    return {f"{GEN_DIR}/{suite.name}/{name}": text for name, text in files.items()}


