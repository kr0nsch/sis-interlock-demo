@dataclass(frozen=True)
class Table:
    """Одна таблица: уровень 1 (F_VoteEval) или 2 (FB_Voting)."""

    level: int
    arch: int
    policy: int
    kind: int = 0  # только уровень 2

    @property
    def arch_name(self) -> str:
        return M.ARCH_NAME[self.arch]

    @property
    def tag(self) -> str:
        """Часть имени: 2oo3VT (уровень 1), 2oo3VTAI (уровень 2)."""
        kind = KIND_ABBR[self.kind] if self.level == 2 else ""
        return f"{self.arch_name}{POLICY_ABBR[self.policy]}{kind}"

    @property
    def test_name(self) -> str:
        prefix = "Eval" if self.level == 1 else "Fb"
        return f"VoteTable_{prefix}{self.tag}_MatchesModel"

    @property
    def method_name(self) -> str:
        return "".join(self.test_name.split("_")[1:])

    def expected(self) -> list[int]:
        if self.level == 1:
            return M.eval_table(self.arch, self.policy)
        return M.fb_table(self.arch, self.policy, self.kind)


def all_tables() -> list[Table]:
    level1 = [Table(1, a, p) for a in ARCHS for p in POLICY_ABBR]
    level2 = [Table(2, a, p, k) for a in ARCHS for p in POLICY_ABBR for k in KIND_ABBR]
    return level1 + level2


@dataclass(frozen=True)
class Suite:
    name: str
    instance: str
    comment: str
    tables: tuple[Table, ...]

    def asserts(self) -> int:
        return sum(len(t.expected()) for t in self.tables)


def plan_suites() -> list[Suite]:
    """Наборы: уровень 1 — один; уровень 2 — по набору на таблицу 2oo3 (512 строк) и один на
    остальные схемы (1oo1, 1oo2, 2oo2: 816 строк)."""
    tables = all_tables()
    level1 = tuple(t for t in tables if t.level == 1)
    big = [t for t in tables if t.level == 2 and t.arch == M.VOTE_2OO3]
    small = tuple(t for t in tables if t.level == 2 and t.arch != M.VOTE_2OO3)
    suites = [Suite("FB_VoteTableEval_Test", "fbVoteTableEvalTest", "F_VoteEval: 12 таблиц, 300 строк", level1)]
    for t in big:
        suites.append(
            Suite(
                f"FB_VoteTable{t.tag}_Test",
                f"fbVoteTable{t.tag}Test",
                f"FB_Voting: {t.arch_name} {POLICY_ABBR[t.policy]} {KIND_ABBR[t.kind]}, 512 строк",
                (t,),
            )
        )
    suites.append(Suite("FB_VoteTableFbSmall_Test", "fbVoteTableFbSmallTest", "FB_Voting: 1oo1, 1oo2, 2oo2", small))
    return suites


# --- Сообщения ассертов --------------------------------------------------------------------------


def result_text(value: int, n: int, level: int) -> str:
    trip = value & 1
    deg = (value >> 1) & 1
    arch_index = (value >> 2) & 7
    arch = next(a for a, i in M.ARCH_INDEX.items() if i == arch_index)
    text = f"trip={trip} deg={deg} eff={M.ARCH_NAME[arch]}"
    if level == 2:
        text += " byp=" + "".join(str((value >> (5 + k)) & 1) for k in range(n))
    return text


def row_message(table: Table, row: int, value: int) -> str:
    n = M.arch_channels(table.arch)
    if table.level == 1:
        states = M.eval_row_states(table.arch, row)[:n]
        chans = "".join(STATE_LETTER[s] for s in states)
        head = f"Eval {table.arch_name} {POLICY_ABBR[table.policy]} r={row} c={chans}"
    else:
        inp = M.fb_row_inputs(table.arch, row)
        chans = "/".join(
            ("D" if inp.demand[k] else "-") + ("V" if inp.valid[k] else "-") + ("B" if inp.bypass_req[k] else "-")
            for k in range(n)
        )
        head = f"Fb {table.arch_name} {POLICY_ABBR[table.policy]} {KIND_ABBR[table.kind]} r={row} c={chans}"
    return f"{head}: {result_text(value, n, table.level)}"


