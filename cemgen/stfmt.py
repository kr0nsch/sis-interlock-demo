"""Запись литералов ST и заголовков сгенерированных файлов (DESIGN.md, 10.3).

* Длительности: ``T#`` и части от часов к миллисекундам без нулевых частей (``T#2S``,
  ``T#100MS``, ``T#14M59S900MS``, ``T#8H``); ноль — ``T#0S``.
* REAL: кратчайшая десятичная запись, которая даёт то же float32, всегда с точкой (``0.9``,
  ``1.6``, ``85.0``, ``16.16``).
* Маски: ``16#XXXX`` (четыре цифры).
"""

from __future__ import annotations

import math
from collections.abc import Iterable
from dataclasses import dataclass
from decimal import Decimal

from cemgen import DISCLAIMER, __version__, limits
from cemgen.model import Matrix
from cemgen.refmodel import f32

DOC_SECTION = "docs/DESIGN.md, раздел «10. Генератор cemgen»; docs/cause_effect_matrix.md"


class GenerationError(Exception):
    """Сгенерированный текст нарушает правила (длина строки и т. п.) — ошибка генератора."""


def st_time(ms: int, prefix: str = "T#") -> str:
    """Длительность в мс → литерал ST."""
    if ms < 0:
        raise GenerationError(f"отрицательная длительность {ms} мс")
    if ms == 0:
        return f"{prefix}0S"
    parts = []
    hours, rest = divmod(ms, 3_600_000)
    minutes, rest = divmod(rest, 60_000)
    seconds, millis = divmod(rest, 1000)
    for value, unit in ((hours, "H"), (minutes, "M"), (seconds, "S"), (millis, "MS")):
        if value:
            parts.append(f"{value}{unit}")
    return prefix + "".join(parts)


def st_ltime(ms: int) -> str:
    return st_time(ms, "LTIME#")


def st_real(value: float | Decimal) -> str:
    """REAL → кратчайшая запись с точкой, без экспоненты."""
    x = float(value)
    if math.isnan(x) or math.isinf(x):
        raise GenerationError(f"REAL {x} не записывается литералом")
    target = f32(x)
    if target == 0.0:
        return "0.0"
    text = ""
    for digits in range(1, 10):
        candidate = f"{target:.{digits}g}"
        if f32(float(candidate)) == target:
            text = candidate
            break
    plain = format(Decimal(text), "f")
    return plain if "." in plain else plain + ".0"


def st_word(mask: int) -> str:
    return f"16#{mask & 0xFFFF:04X}"


def st_byte(value: int) -> str:
    return f"16#{value & 0xFF:02X}"


def st_bool(value: bool) -> str:
    return "TRUE" if value else "FALSE"


def comment_lines(text: str, width: int = limits.ST_LINE_MAX, indent: str = "", prefix: str = "// ") -> list[str]:
    """Комментарий ``//``, перенесённый по словам так, чтобы строка не длиннее ``width``."""
    room = width - len(indent) - len(prefix)
    lines: list[str] = []
    current = ""
    for word in text.split():
        if current and len(current) + 1 + len(word) > room:
            lines.append(indent + prefix + current)
            current = word
        else:
            current = f"{current} {word}" if current else word
    if current:
        lines.append(indent + prefix + current)
    return lines


@dataclass(frozen=True)
class HeaderInfo:
    """Данные заголовка сгенерированных файлов: из шапки матрицы и SHA-256 сетки."""

    document: str
    object: str
    revision: str
    date: str
    author: str
    digest: str

    @classmethod
    def of(cls, matrix: Matrix) -> HeaderInfo:
        h = matrix.header
        return cls(h.document, h.object, h.revision, h.date, h.author, matrix.grid_digest)

    def generated_lines(self) -> list[str]:
        """Первые три строки (без ``//``): общие для объявлений, тел и документов."""
        return [
            f"AUTO-GENERATED by cemgen {__version__} — не редактировать: правьте матрицу и запустите",
            "  python -m cemgen generate <файл матрицы .csv или .xlsx>",
            f"Матрица: {self.document}, объект {self.object}, ревизия {self.revision} от {self.date}, "
            f"SHA-256 сетки {self.digest}",
        ]


def st_header(info: HeaderInfo, purpose: str, *, declaration: bool = True) -> list[str]:
    """Заголовок ST-файла: у объявлений — полный (10.3), у тел — первые три строки."""
    lines: list[str] = []
    for text in info.generated_lines():
        lines.extend(_wrap_prefixed("// ", text, "//   "))
    if not declaration:
        return lines
    lines.extend(_wrap_prefixed("// Назначение: ", purpose, "//             "))
    lines.extend(_wrap_prefixed("// Автор:      ", f"{info.author}; код — генератор cemgen", "//             "))
    lines.append(f"// Версия:     {__version__}")
    lines.append(f"// Документ:   {DOC_SECTION}")
    lines.extend(_wrap_prefixed("// ВНИМАНИЕ:   ", DISCLAIMER, "//             "))
    return lines


HEADER_WIDTH = 100


def _wrap_prefixed(first: str, text: str, rest: str, width: int = HEADER_WIDTH) -> list[str]:
    """Текст после префикса первой строки; продолжения — с префиксом ``rest``."""
    words: list[str] = []
    for word in text.split(" "):
        if words and word in ("—", "–", "→"):
            words[-1] += " " + word  # тире не начинает строку
        else:
            words.append(word)
    lines: list[str] = []
    current = first
    started = False
    for word in words:
        if started and len(current) + 1 + len(word) > width:
            lines.append(current)
            current = rest + word
        else:
            current = current + (" " if started else "") + word
            started = True
    lines.append(current)
    return lines


def join_lines(lines: Iterable[str]) -> str:
    """Текст файла: строки через LF, один LF в конце; проверка длины строк и хвостовых пробелов."""
    out: list[str] = []
    for line in lines:
        line = line.rstrip()
        if len(line) > limits.ST_LINE_MAX:
            raise GenerationError(f"строка длиннее {limits.ST_LINE_MAX} символов: {line[:60]}…")
        out.append(line)
    while out and not out[-1]:
        out.pop()
    return "\n".join(out) + "\n"


def pack(items: list[str], first: str, cont: str, last_suffix: str, width: int = limits.ST_LINE_MAX) -> list[str]:
    """Элементы через запятую по строкам не длиннее ``width``.

    Первая строка начинается с ``first``, продолжения — с ``cont``; после последнего элемента —
    ``last_suffix`` (например ``");"``).
    """
    lines: list[str] = []
    current = first
    fresh = True
    for index, item in enumerate(items):
        piece = item + ("," if index < len(items) - 1 else last_suffix)
        candidate = current + ("" if fresh else " ") + piece
        if not fresh and len(candidate) > width:
            lines.append(current)
            current = cont + piece
        else:
            current = candidate
        fresh = False
    lines.append(current)
    return lines
